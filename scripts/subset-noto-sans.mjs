// scripts/subset-noto-sans.mjs
// ONE-TIME font subsetting script. Run once, commit the output.
// Produces: src/pdf/notoSansBase64.ts
//
// Font source: scripts/fonts/NotoSans-Regular.ttf + NotoSans-Bold.ttf
//   (downloaded from Google Fonts static CDN, committed for reproducibility)
//
// Character coverage:
//   Basic Latin:          U+0020–U+007E (printable ASCII)
//   Latin-1 Supplement:   U+00A0–U+00FF (accented Latin: é à ñ ß ç ö ü etc.)
//   Latin Extended-A:     U+0100–U+017F (Polish ą ę ć ł ś ź ż, Czech ň ř, etc.)
//   Latin Extended-B:     U+0180–U+024F
//   Euro sign:            U+20AC (Currency Symbols block — NOT in Latin/Latin-Ext blocks;
//                         must be added explicitly per RESEARCH.md GLYPH COVERAGE VERIFICATION)
//
// The €/U+20AC inclusion is a justified technical clarification of CONTEXT.md D-10
// ("Latin + Latin-Ext subset only") — the Euro sign is not in the Latin or Latin-Ext
// Unicode blocks, so it must be explicitly included.
//
// Regenerate: node scripts/subset-noto-sans.mjs

import { createRequire } from 'module';
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const subsetFont = require('subset-font');

// Build the character string for subsetting.
// We include every codepoint in the desired ranges.
function buildCharacterSet() {
  const ranges = [
    [0x0020, 0x007E],  // Basic Latin (printable ASCII)
    [0x00A0, 0x00FF],  // Latin-1 Supplement
    [0x0100, 0x017F],  // Latin Extended-A
    [0x0180, 0x024F],  // Latin Extended-B
  ];
  const chars = [];
  for (const [start, end] of ranges) {
    for (let cp = start; cp <= end; cp++) {
      chars.push(String.fromCodePoint(cp));
    }
  }
  // U+20AC Euro sign — explicitly included (Currency Symbols block, NOT Latin/Latin-Ext)
  chars.push('€');
  return chars.join('');
}

async function main() {
  const fontsDir = join(__dirname, 'fonts');
  const regularTtf = readFileSync(join(fontsDir, 'NotoSans-Regular.ttf'));
  const boldTtf = readFileSync(join(fontsDir, 'NotoSans-Bold.ttf'));

  console.log(`Noto Sans Regular TTF: ${regularTtf.length} bytes`);
  console.log(`Noto Sans Bold TTF: ${boldTtf.length} bytes`);

  const characters = buildCharacterSet();
  console.log(`Subsetting ${characters.length} characters (Latin + Latin-Ext + U+20AC)...`);

  const [regularSubset, boldSubset] = await Promise.all([
    subsetFont(regularTtf, characters, { targetFormat: 'truetype' }),
    subsetFont(boldTtf, characters, { targetFormat: 'truetype' }),
  ]);

  console.log(`Regular subset: ${regularSubset.length} bytes`);
  console.log(`Bold subset: ${boldSubset.length} bytes`);

  const regularBase64 = regularSubset.toString('base64');
  const boldBase64 = boldSubset.toString('base64');

  console.log(`Regular base64 length: ${regularBase64.length} chars`);
  console.log(`Bold base64 length: ${boldBase64.length} chars`);

  // Ensure the output directory exists
  const outDir = join(__dirname, '..', 'src', 'pdf');
  mkdirSync(outDir, { recursive: true });

  const outPath = join(outDir, 'notoSansBase64.ts');

  const output = `// AUTO-GENERATED by scripts/subset-noto-sans.mjs — do not edit manually.
// Noto Sans Regular + Bold, Latin + Latin-Ext + Euro sign (U+20AC) subset.
// Regenerate: node scripts/subset-noto-sans.mjs
//
// Character coverage:
//   Basic Latin (U+0020–U+007E), Latin-1 Supplement (U+00A0–U+00FF),
//   Latin Extended-A (U+0100–U+017F), Latin Extended-B (U+0180–U+024F),
//   Euro sign (U+20AC — explicitly included; NOT in Latin/Latin-Ext blocks).
//
// Raw base64 (no data URI prefix) — jsPDF addFileToVFS expects raw base64 string.

export const notoSansRegularBase64: string =
  '${regularBase64}';

export const notoSansBoldBase64: string =
  '${boldBase64}';
`;

  writeFileSync(outPath, output);
  console.log(`✓ Written: ${outPath}`);
  console.log(`  Total file size: ${output.length} bytes (~${(output.length / 1024).toFixed(1)} KB)`);
}

main().catch(err => {
  console.error('subset-noto-sans failed:', err);
  process.exit(1);
});
